import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('./',import.meta.url);
const names=['routing.mjs','model-catalog.mjs','response-demo.mjs','workload.mjs','case-scenarios.mjs','live.js','supervisor.js','app.js'];
// Fail early on encoding damage before updating or packaging browser artifacts.
for(const name of [...names,'index.html','style.css','README.md']){
 const source=await readFile(new URL(name,root),'utf8');
 if(/[\uFFFD\u00C2\u00C3]/.test(source)||((name.endsWith('.html')||name.endsWith('.md'))&&/\s\?\s/.test(source))||/Backend configuration \? Publish/.test(source))throw Error('Broken encoding or stray question-mark separator in '+name);
}
const parts=await Promise.all(names.map(async name=>(await readFile(new URL(name,root),'utf8')).replace(/^import [^;]+;/gm,'').replace(/^export /gm,'')));
const bundle='// Generated by node omnirouter/build.mjs. Edit source modules, then rebuild.\n(()=>{\n'+parts.map((s,i)=>i===0?s.replace('function route(', 'function baseRoute('):s).join('\n')+'\n})();\n';
await writeFile(new URL('bundle.js',root),bundle);
const hash=createHash('sha256').update(bundle).digest('hex').slice(0,12);
const html=await readFile(new URL('index.html',root),'utf8');
await writeFile(new URL('index.html',root),html.replace(/src="bundle\.js(?:\?v=[^"]*)?"/,`src="bundle.js?v=${hash}"`));
console.log('Built browser bundle');
